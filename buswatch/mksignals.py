#!/usr/bin/env python3
# bakes the v850 signal tables (../qemu/v850_messages.py, the same ones the car emulator speaks)
# into bussignals.h for the on-unit bus watch app. run from the repo root or via make.
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
ICC2 = os.environ.get('ICC2_DIR') or os.path.normpath(os.path.join(REPO, '..', '..', '..', 'ICC2'))
sys.path.insert(0, os.path.join(ICC2, 'qemu'))
import v850_messages

OUT = os.path.join(HERE, 'bussignals.h')


def cstr(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def cname(msg):
    return ''.join(ch if ch.isalnum() else '_' for ch in msg)


