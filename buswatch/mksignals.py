def main():
    messages = sorted(v850_messages.MESSAGES.items(), key=lambda kv: (kv[1][0], kv[1][1]))
    lines = []
    lines.append('/*')
    lines.append(' * generated by mksignals.py from ../qemu/v850_messages.py, do not edit.')
    lines.append(' * the v850 codec tables (channel, message id, version, length, {signal: (byte, start bit, bits)}).')
    lines.append(' * a wide signal stores its low byte at `byte` and grows into lower indexed bytes, so')
    lines.append(' * value = (d[byte-n+1 .. byte] big endian little endian concat) >> bit. see v850.py pack().')
    lines.append(' */')
    lines.append('#ifndef BUSSIGNALS_H')
    lines.append('#define BUSSIGNALS_H')
    lines.append('')
    lines.append('struct bussig {')
    lines.append('    const char *name;')
    lines.append('    unsigned char byte, bit, bits;')
    lines.append('};')
    lines.append('')
    lines.append('struct busmsg {')
    lines.append('    const char *name;')
    lines.append('    unsigned char ch, id, version, len, nsigs;')
    lines.append('    const struct bussig *sigs;')
    lines.append('};')
    lines.append('')
    count = 0
    for msg, (ch, mid, version, length, signals) in messages:
        lines.append('static const struct bussig sig_%s[] = {' % cname(msg))
        for name, (byte, bit, bits) in signals.items():
            lines.append('    { %s, %u, %u, %u },' % (cstr(name), byte, bit, bits))
            count += 1
        lines.append('};')
        lines.append('')
    lines.append('#define BUS_SIGNAL_COUNT %d' % count)
    lines.append('')
    lines.append('static const struct busmsg bus_messages[] = {')
    for msg, (ch, mid, version, length, signals) in messages:
        lines.append('    { %s, 0x%02x, 0x%02x, %u, %u, %u, sig_%s },' %
                     (cstr(msg), ch, mid, version, length, len(signals), cname(msg)))
    lines.append('};')
    lines.append('')
    lines.append('#define BUS_MESSAGE_COUNT ((int)(sizeof bus_messages / sizeof bus_messages[0]))')
    lines.append('')
    lines.append('struct busbutton {')
    lines.append('    const char *name;')
    lines.append('    unsigned char bit;')
    lines.append('};')
    lines.append('')
    lines.append('static const struct busbutton bus_buttons[] = {')
    for bit, name in BUTTONS:
        lines.append('    { %s, %u },' % (cstr(name), bit))
    lines.append('};')
    lines.append('')
    lines.append('#define BUS_BUTTON_COUNT ((int)(sizeof bus_buttons / sizeof bus_buttons[0]))')
    lines.append('')
    lines.append('struct bushint {')
    lines.append('    const char *msg, *sig, *text;')
    lines.append('    int value;')
    lines.append('};')
    lines.append('')
    lines.append('static const struct bushint bus_hints[] = {')
    for msg, sig, value, text in hints():
        lines.append('    { %s, %s, %s, %d },' % (cstr(msg), cstr(sig), cstr(text), value))
    lines.append('};')
    lines.append('')
    lines.append('#define BUS_HINT_COUNT ((int)(sizeof bus_hints / sizeof bus_hints[0]))')
    lines.append('')
    lines.append('#endif')
    lines.append('')

    with open(OUT, 'w') as f:
        f.write('\n'.join(lines))
    print('wrote', OUT, '(%d signals in %d messages)' % (count, len(messages)))


if __name__ == '__main__':
    main()
